function getDynamicThumbnail(topicText = '') {
  const text = topicText.toLowerCase();
  if (text.includes('space') || text.includes('star') || text.includes('black hole') || text.includes('galaxy')) {
    return THUMBNAILS_POOL[0];
  }
  if (text.includes('ocean') || text.includes('sea') || text.includes('trench') || text.includes('water')) {
    return THUMBNAILS_POOL[1];
  }
  if (text.includes('brain') || text.includes('sleep') || text.includes('dream') || text.includes('mind')) {
    return THUMBNAILS_POOL[2];
  }
  if (text.includes('mountain') || text.includes('everest') || text.includes('time') || text.includes('earth')) {
    return THUMBNAILS_POOL[3];
  }
  if (text.includes('ai') || text.includes('robot') || text.includes('tech') || text.includes('cyber')) {
    return THUMBNAILS_POOL[4];
  }
  if (text.includes('city') || text.includes('ancient') || text.includes('pyramid') || text.includes('history')) {
    return THUMBNAILS_POOL[5];
  }
  if (text.includes('money') || text.includes('bitcoin') || text.includes('crypto') || text.includes('gold')) {
    return THUMBNAILS_POOL[6];
  }
  // Random from pool
  return THUMBNAILS_POOL[Math.floor(Math.random() * THUMBNAILS_POOL.length)];
}

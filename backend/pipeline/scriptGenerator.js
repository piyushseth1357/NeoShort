export async function generateShortScript(niche, topic = null, language = "Hindi") {
  const apiKey = process.env.AI_API_KEY;
  const targetNiche = niche || "Mind-Blowing Facts & Science";
  const isHindi = (language || '').toLowerCase().includes('hindi') || (language || '').toLowerCase().includes('hi');

  // If user passed a custom topic or if Gemini API key starts with AIzaSy
  if (apiKey && apiKey.startsWith("AIzaSy")) {
    try {
      const prompt = `You are a viral YouTube Shorts scriptwriter for channel 'Fact & Mistery'.
Generate an ultra-engaging, 40-second YouTube Short script about: "${topic || targetNiche}".
Niche: ${targetNiche}
Language: ${isHindi ? 'Hindi (conversational, easy-to-understand storytelling Devanagari Hindi)' : 'English'}

Strict requirements:
1. First 3 seconds MUST have an irresistible psychological hook.
2. Fast-paced, concise voiceover narration (85 to 105 words total).
3. Climax & Call to action to subscribe to Fact & Mistery.

Return ONLY a valid JSON object without markdown fences, with these exact keys:
{
  "title": "Clickable high-CTR title with emojis and #shorts",
  "hook": "Exact first 5-8 words spoken",
  "narration": "Full voiceover text to be spoken by AI voice from start to finish",
  "keywords": ["scene1", "scene2", "scene3"],
  "tags": ["#shorts", "#facts", "#trending"]
}`;

      const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { temperature: 0.85, responseMimeType: "application/json" }
        })
      });

      const data = await response.json();
      if (data.candidates && data.candidates[0]?.content?.parts[0]?.text) {
        const rawText = data.candidates[0].content.parts[0].text;
        const cleanJson = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
        const scriptData = JSON.parse(cleanJson);
        
        // Pick dynamic thumbnail based on keywords
        scriptData.thumbnail = getDynamicThumbnail(topic || targetNiche);
        return scriptData;
      }
    } catch (err) {
      console.warn("[Gemini API] Custom generation fallback:", err.message);
    }
  }

  // Dynamic Procedural Engine: Guaranteed Fresh Every Single Call!
  return getProceduralScript(targetNiche, topic, isHindi);
}

